const { chromium } = require('C:/Users/Lenovo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('fs');
const path = require('path');
const {pathToFileURL}=require('url');
(async()=>{
 const root=path.resolve(__dirname,'../../..');
 const out=path.join(root,'reports/2026-09-21-starter78-feedback-pilot');
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:1080}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.join(out,'index.html')).href);
 await page.locator('#count').waitFor();
 const firstCount=await page.locator('article:visible').count();
 if(firstCount!==78)throw Error('Missing first phase records');
 await page.screenshot({path:path.join(out,'qa-desktop.png')});
 await page.selectOption('#phase','transfer');
 const transferCount=await page.locator('article:visible').count();
 if(transferCount!==30)throw Error('Missing transfer records');
 await page.fill('#query','no-such-id');
 if(await page.locator('article:visible').count())throw Error('Filter failed');
 await page.reload();
 if(await page.inputValue('#query')!=='no-such-id')throw Error('URL restore failed');
 await page.fill('#query','');await page.selectOption('#phase','first');
 await page.setViewportSize({width:390,height:844});
 await page.goto(pathToFileURL(path.join(out,'index.html')).href);
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 if(overflow)throw Error('Mobile document overflow');
 await page.screenshot({path:path.join(out,'qa-mobile.png')});
 const assets=await page.locator('img').evaluateAll(imgs=>imgs.map(i=>new URL(i.getAttribute('src'),location.href).pathname));
 const missing=assets.filter(p=>!fs.existsSync(decodeURIComponent(p.replace(/^\//,''))));
 if(missing.length)throw Error('Missing image '+missing[0]);
 if(errors.length)throw Error(errors.join('\n'));
 fs.writeFileSync(path.join(out,'browser-qa.json'),JSON.stringify({desktop:[1440,1080],mobile:[390,844],firstCount,transferCount,queryAndURLRestore:true,mobileOverflow:overflow,missingImages:missing,pageErrors:errors},null,2));
 await browser.close();
 console.log('Report browser QA PASS');
})().catch(e=>{console.error(e);process.exit(1)});
